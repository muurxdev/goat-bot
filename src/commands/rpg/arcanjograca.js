/**
 * Comando .arcanjograca — Graça divina dos arcanjos: ficha de cada nível (1 a 11).
 *
 * Junta os antigos .arcanjo1 … .arcanjo11, que eram 11 arquivos com o mesmo
 * cartão e só o número trocado (unificado em 2026-09-18). Os nomes antigos
 * continuam funcionando como atalhos: ".arcanjo5" abre o nível 5.
 */

const F = require('../../utils/formato')

const CARTAO = { emoji: "🪽", titulo: "GRAÇA DIVINA DOS ARCANJOS", frase: "Poder supremo concedido pela Suprema Divindade para reinar sobre os céus." }
const NIVEIS = [
    { cp: "+150 pts", raridade: "Comum ⚪" },
    { cp: "+300 pts", raridade: "Rara 💠" },
    { cp: "+450 pts", raridade: "Comum ⚪" },
    { cp: "+600 pts", raridade: "Rara 💠" },
    { cp: "+750 pts", raridade: "Lendária 🌟" },
    { cp: "+900 pts", raridade: "Rara 💠" },
    { cp: "+1050 pts", raridade: "Comum ⚪" },
    { cp: "+1200 pts", raridade: "Rara 💠" },
    { cp: "+1350 pts", raridade: "Comum ⚪" },
    { cp: "+1500 pts", raridade: "Lendária 🌟" },
    { cp: "+1650 pts", raridade: "Comum ⚪" }
]

/** Nível pedido: pelo argumento (".arcanjograca 5") ou pelo atalho digitado (".arcanjo5"). */
function nivelPedido(args, digitado) {
    const doArg = parseInt(args[0], 10)
    if (Number.isInteger(doArg)) return doArg
    const doAtalho = String(digitado || '').match(/(\d+)$/)
    return doAtalho ? parseInt(doAtalho[1], 10) : null
}

module.exports = {
    name: "arcanjograca",
    aliases: ["arc-1","arc-2","arc-3","arc-4","arc-5","arc-6","arc-7","arc-8","arc-9","arc-10","arc-11","arc1","arc2","arc3","arc4","arc5","arc6","arc7","arc8","arc9","arc10","arc11","arcanjo1","arcanjo2","arcanjo3","arcanjo4","arcanjo5","arcanjo6","arcanjo7","arcanjo8","arcanjo9","arcanjo10","arcanjo11"],
    category: "rpg",
    subcategory: "Arcanjos",
    description: "Graça divina dos arcanjos: lore e ficha de cada nível, do 1 ao 11",
    usage: '[nível]',
    examples: ["— lore e tabela dos 11 níveis", "5 — ficha do nível 5"],
    cooldownMs: 1500,
    execute: async ({ reply, args = [], commandName = '', prefix = '.' }) => {
        const n = nivelPedido(args, commandName)
        if (n === null) {
            return reply(F.tela({
                emoji: CARTAO.emoji, titulo: CARTAO.titulo, intro: CARTAO.frase, prefix,
                secoes: [{ emoji: '📊', titulo: 'Níveis', linhas: NIVEIS.map((x, i) => `• *Nível ${i + 1}:* ${x.cp} · ${x.raridade}`) }],
                proximos: [{ nome: "arcanjograca", args: '5', oque: 'ver a ficha de um nível' }]
            }))
        }
        if (n < 1 || n > NIVEIS.length) {
            return reply(F.tela({
                emoji: '⚠️', titulo: 'Nível que não existe', prefix,
                intro: `${CARTAO.titulo} vai do nível 1 ao ${NIVEIS.length}.`,
                proximos: [{ nome: "arcanjograca", oque: 'ver todos os níveis' }]
            }))
        }
        const x = NIVEIS[n - 1]
        return reply(F.tela({
            emoji: CARTAO.emoji, titulo: CARTAO.titulo, intro: CARTAO.frase, prefix,
            secoes: [{ emoji: '📊', titulo: `Nível ${n}`, linhas: [
                F.campo('Grau de maestria', `Nível ${n}`),
                F.campo('Poder de combate (CP)', x.cp),
                F.campo('Raridade', x.raridade)
            ] }],
            proximos: [
                n < NIVEIS.length ? { nome: "arcanjograca", args: String(n + 1), oque: 'próximo nível' } : null,
                { nome: "arcanjograca", oque: 'todos os níveis' }
            ].filter(Boolean)
        }))
    }
}
