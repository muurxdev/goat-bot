/**
 * Converte texto para estilo unicode mapeado
 */
function toUnicodeFont(text, style) {
    const map = FONT_MAPS[style];
    if (!map) return text;
    return String(text).split('').map(ch => map[ch] || ch).join('');
}

/**
 * Inverte texto ponta-cabeça
 */
function toUpsideDown(text) {
    return String(text).split('').reverse().map(ch => UPSIDE_DOWN_MAP[ch] || ch).join('');
}

/**
 * Efeito Vaporwave / Fullwidth
 */
function toVaporwave(text) {
    return String(text).split('').map(ch => {
        const code = ch.charCodeAt(0);
        if (code === 32) return '　';
        if (code >= 33 && code <= 126) return String.fromCharCode(code + 65248);
        return ch;
    }).join(' ');
}

/**
 * Converte para Código Morse
 */
function toMorse(text) {
    return String(text).toUpperCase().split('').map(ch => MORSE_MAP[ch] || ch).join(' ');
}

/**
 * Converte texto para Binário
 */
function toBinary(text) {
    return Buffer.from(String(text), 'utf8')
        .toJSON()
        .data.map(b => b.toString(2).padStart(8, '0'))
        .join(' ');
}

/**
 * Converte texto para Hexadecimal
 */
function toHex(text) {
    return Buffer.from(String(text), 'utf8').toString('hex').toUpperCase().match(/.{1,2}/g).join(' ');
}

/**
 * Converte para Base64
 */
function toBase64(text) {
    return Buffer.from(String(text), 'utf8').toString('base64');
}

/**
 * Leetspeak (1337)
 */
function toLeet(text) {
    return String(text).split('').map(ch => LEET_MAP[ch] || ch).join('');
}

/**
 * Texto tachado / strike-through
 */
function toStrike(text) {
    return String(text).split('').map(ch => ch + '\u0336').join('');
}

/**
 * Texto sublinhado / underline
 */
function toUnderline(text) {
    return String(text).split('').map(ch => ch + '\u0332').join('');
}

/**
 * Cifra de César
 */
function toCaesar(text, shift = 3) {
    const s = ((shift % 26) + 26) % 26;
    return String(text).replace(/[a-zA-Z]/g, ch => {
        const base = ch <= 'Z' ? 65 : 97;
        return String.fromCharCode(((ch.charCodeAt(0) - base + s) % 26) + base);
    });
}

/**
 * Efeito Zalgo / Glitch
 */
function toZalgo(text) {
    const zalgoUp = ['\u030d', '\u030e', '\u0304', '\u0305', '\u033f', '\u0311', '\u0306', '\u0310'];
    const zalgoDown = ['\u0316', '\u0317', '\u0318', '\u0319', '\u031c', '\u0320', '\u0324', '\u0325'];
    return String(text).split('').map(ch => {
        if (/\s/.test(ch)) return ch;
        return ch + zalgoUp[Math.floor(Math.random() * zalgoUp.length)] + zalgoDown[Math.floor(Math.random() * zalgoDown.length)];
    }).join('');
}

